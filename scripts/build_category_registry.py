def main():
 rows=list(csv.DictReader(SOURCE.open(encoding='utf-8-sig')))
 mapping={}
 for asset, names in GROUPS.items():
  for name in names.split('|'):
   if name in mapping: raise ValueError(f'Duplicate: {name}')
   mapping[name]=asset
 baseline={r['categoria'] for r in rows}
 if baseline != mapping.keys():
  raise ValueError(f'Missing {baseline-mapping.keys()}, extra {mapping.keys()-baseline}')
 source=['// Generated by scripts/build_category_registry.py. Catalogue labels unchanged.',
         "import 'cineus_assets.dart';", '', 'const categoryAssetRegistry = <String, CineusAssetId>{']
 source += [f"  '{name}': CineusAssetId.{mapping[name]}," for name in sorted(mapping)]
 source += ['};', '']
 (ROOT/'lib/presentation/visuals/category_assets.dart').write_text('\n'.join(source),encoding='utf-8')
 OUT.mkdir(parents=True,exist_ok=True)
 for r in rows:
  asset=mapping[r['categoria']]
  r['asset_final']=asset
  r['decisao']='fallback próprio: rótulo amplo/ambíguo' if asset=='categoryFallback' else 'arte própria compartilhada por metáfora visual'
 with (OUT/'CATEGORIAS.csv').open('w',encoding='utf-8-sig',newline='') as f:
  w=csv.DictWriter(f,fieldnames=list(rows[0]));w.writeheader();w.writerows(rows)
 (OUT/'categorias_mapeadas.json').write_text(json.dumps(mapping,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
 print(f'{len(mapping)} explicit decisions; {len(set(mapping.values()))} visual destinations.')
if __name__=='__main__':main()
