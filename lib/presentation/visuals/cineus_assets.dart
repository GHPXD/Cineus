abstract final class CineusAssets {
  static CineusAssetId forAchievement(String id) => switch (id) {
    'poster_first' => CineusAssetId.badgePosterFirst,
    'poster_perfect' => CineusAssetId.badgePosterPerfect,
    'colors_first' => CineusAssetId.badgeColorsFirst,
    'colors_25' => CineusAssetId.badgeColors25,
    'colors_excellent' => CineusAssetId.badgeColorsExcellent,
    'colors_stages_3' => CineusAssetId.badgeColorsStages3,
    'first_win' => CineusAssetId.badgeFirstWin,
    'perfect' => CineusAssetId.badgePerfect,
    'streak_7' => CineusAssetId.badgeStreak7,
    'streak_30' => CineusAssetId.badgeStreak30,
    'games_50' => CineusAssetId.badgeGames50,
    'stages_5' => CineusAssetId.badgeStages5,
    'tickets_100' => CineusAssetId.badgeTickets100,
    _ => CineusAssetId.completed,
  };
  static const brandMark = 'assets/brand/cineus_mark.png';
  static final _normalizedCategories = {
    for (final entry in categoryAssetRegistry.entries)
      entry.key.toLowerCase(): entry.value,
  };
  static CineusAssetId forCategory(String category) =>
      _normalizedCategories[category.trim().toLowerCase()] ??
      CineusAssetId.categoryFallback;
  static CineusAssetId forHint(ExtraHint hint) => switch (hint) {
    ExtraHint.director => CineusAssetId.hintDirector,
    ExtraHint.year => CineusAssetId.hintYear,
    ExtraHint.runtime => CineusAssetId.hintRuntime,
  };
}
